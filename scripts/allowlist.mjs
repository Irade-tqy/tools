#!/usr/bin/env node
// Populate the clipboard password allowlist. Hashing happens inside Postgres
// (crypt()/gen_salt('bf')), so no bcrypt dependency and no plaintext ever lands in the
// repo. Passwords come from .env.local (TOOLS_CLIPBOARD_PASSWORDS) or argv, in
// `label:password` or bare `password` form.
//
//   node scripts/allowlist.mjs                       # sync from .env.local
//   node scripts/allowlist.mjs 'work:hunter2'        # add/rotate one entry
//   node scripts/allowlist.mjs --list                # show labels only
//   node scripts/allowlist.mjs --rotate              # re-hash existing labels
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import pg from 'pg';
import { connectDb, env, rootDir } from './lib.mjs';

const args = process.argv.slice(2);
const flags = new Set(args.filter((a) => a.startsWith('--')));
const specs = args.filter((a) => !a.startsWith('--'));

const client = await connectDb();

function parseSpecs(list) {
  return list.map((spec, i) => {
    const at = spec.indexOf(':');
    if (at > 0) return { label: spec.slice(0, at), password: spec.slice(at + 1) };
    return { label: `secret-${i + 1}`, password: spec };
  });
}

try {
  if (flags.has('--list')) {
    const { rows } = await client.query(
      'select label, created_at from public.clipboard_secret order by id',
    );
    if (!rows.length) console.log('allowlist is empty');
    for (const r of rows) console.log(`${r.label}\t${r.created_at.toISOString()}`);
    process.exit(0);
  }

  let entries = specs.length ? parseSpecs(specs) : [];
  if (!entries.length && env.TOOLS_CLIPBOARD_PASSWORDS) {
    entries = parseSpecs(
      env.TOOLS_CLIPBOARD_PASSWORDS.split(',')
        .map((s) => s.trim())
        .filter(Boolean),
    );
  }
  if (!entries.length) {
    console.error('nothing to do — pass "label:password" args or set TOOLS_CLIPBOARD_PASSWORDS');
    process.exit(1);
  }

  if (flags.has('--rotate')) {
    entries = entries.map((e) => ({ ...e, label: e.label }));
  }

  const lines = ['-- generated by scripts/allowlist.mjs — bcrypt hashes only, safe to keep private', ''];
  for (const entry of entries) {
    // 4 is the floor the site actually needs: short personal codes like a name are the intended
    // use, and clipboard_verify() throttles 10 failures per 15 minutes per code plus 120 global
    // failures per 5 minutes, so a short code cannot be brute-forced quickly.
    if (!entry.password || entry.password.length < 4) {
      console.error(`refusing "${entry.label}": password must be at least 4 characters`);
      process.exit(1);
    }
    const { rows } = await client.query('select crypt($1, gen_salt($2, $3)) as hash', [
      entry.password,
      'bf',
      10,
    ]);
    const hash = rows[0].hash;
    await client.query(
      `insert into public.clipboard_secret (label, pw_hash) values ($1, $2)
       on conflict (label) do update set pw_hash = excluded.pw_hash`,
      [entry.label, hash],
    );
    lines.push(
      `insert into public.clipboard_secret (label, pw_hash) values ('${entry.label}', '${hash}')
       on conflict (label) do update set pw_hash = excluded.pw_hash;`,
    );
    console.log(`set ${entry.label}  hash ${hash.slice(0, 10)}…${hash.slice(-4)}`);
  }

  const out = resolve(rootDir, 'supabase/seed.local.sql');
  writeFileSync(out, `${lines.join('\n')}\n`, { mode: 0o600 });
  console.log(`wrote ${out.replace(`${rootDir}/`, '')} (git-ignored)`);

  const { rows } = await client.query('select count(*)::int as n from public.clipboard_secret');
  console.log(`allowlist now holds ${rows[0].n} secret(s)`);
} catch (err) {
  console.error(`allowlist error: ${err.message}`);
  process.exitCode = 1;
} finally {
  await client.end().catch(() => {});
}
