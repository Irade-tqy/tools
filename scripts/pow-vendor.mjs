#!/usr/bin/env node
// Regenerate supabase/functions/_shared/pow-wasm.ts from scripts/vendor/sha3_wasm_bg.wasm.
//
// The Edge Function bundle cannot fetch DeepSeek's wasm at cold start (an extra network hop
// and a versioned URL that changes), so the 26 KB module ships inside the function as
// base64. Re-run this after replacing the vendored .wasm, then `npm test` — a unit test
// pins the sha256 of the decoded bytes so a silent swap is impossible.
//
//   node scripts/pow-vendor.mjs [--check]
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { rootDir } from './lib.mjs';

const wasmPath = resolve(rootDir, 'scripts/vendor/sha3_wasm_bg.wasm');
const outPath = resolve(rootDir, 'supabase/functions/_shared/pow-wasm.ts');
const check = process.argv.includes('--check');

const bytes = readFileSync(wasmPath);
const digest = createHash('sha256').update(bytes).digest('hex');
const base64 = bytes.toString('base64');

const body =
  `// Generated by scripts/pow-vendor.mjs — do not edit by hand.\n` +
  `// Source: scripts/vendor/sha3_wasm_bg.wasm (${bytes.length} bytes, sha256 ${digest}).\n` +
  `// DeepSeek's proof-of-work module (fe-static.deepseek.com/chat/static/sha3_wasm_bg.*.wasm),\n` +
  `// vendored because it has zero imports and solves the challenge in ~20 ms.\n\n` +
  `export const POW_WASM_SHA256 = '${digest}';\n\n` +
  `export const POW_WASM_BASE64 =\n` +
  // Adjacent string literals are separate statements in JS (ASI), so the chunks must be
  // joined with an explicit `+` — a missing one silently truncates the module.
  (base64.match(/.{1,120}/g) ?? [])
    .map((line, i, all) => `  '${line}'${i === all.length - 1 ? ';' : ' +'}`)
    .join('\n') +
  `\n`;

const current = (() => {
  try {
    return readFileSync(outPath, 'utf8');
  } catch {
    return '';
  }
})();

if (check) {
  if (current !== body) {
    console.error('pow-wasm.ts is out of date — run `node scripts/pow-vendor.mjs`');
    process.exit(1);
  }
  console.log(`pow-wasm.ts matches scripts/vendor/sha3_wasm_bg.wasm (${bytes.length} bytes, sha256 ${digest.slice(0, 16)}…)`);
  process.exit(0);
}

if (current === body) {
  console.log(`unchanged: ${bytes.length} bytes, sha256 ${digest.slice(0, 16)}…`);
} else {
  writeFileSync(outPath, body);
  console.log(`wrote ${outPath}: ${bytes.length} bytes → ${base64.length} base64 chars, sha256 ${digest.slice(0, 16)}…`);
}
