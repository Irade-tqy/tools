#!/usr/bin/env node
// Regenerate src/lib/defaults.ts from .env.local.
//
// The Supabase URL and the anon key are public by design: the anon key ships in the client
// bundle and Row Level Security is what actually guards the data. Hardcoding them means the
// deployed site works with zero setup. Everything else (service role key, DB password,
// clipboard passwords, DeepSeek cookie) stays out of the repo.
//
//   node scripts/defaults-sync.mjs [--check]
//     --check  verify the committed defaults still match .env.local (used in CI)
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { env, rootDir, supabaseUrl } from './lib.mjs';

const target = resolve(rootDir, 'src/lib/defaults.ts');
const checkOnly = process.argv.includes('--check');

/** Decode a Supabase JWT's payload and return its `role` claim ('' if not a JWT). */
function jwtRole(key) {
  const parts = key.split('.');
  if (parts.length !== 3) return '';
  try {
    const payload = JSON.parse(Buffer.from(parts[1], 'base64url').toString('utf8'));
    return typeof payload.role === 'string' ? payload.role : '';
  } catch {
    return '';
  }
}

function render(url, anonKey) {
  return `// Generated by scripts/defaults-sync.mjs — do not edit by hand, and do not put
// secrets here. The URL, the anon key and the function name are public client values (Row
// Level Security enforces access); the service role key, DB password, clipboard passwords,
// admin token and DeepSeek credential never are.
// A unit test (tests/defaults.test.ts) fails the build if a non-anon key lands in here.

export const DEFAULT_SUPABASE_URL = ${JSON.stringify(url)};
export const DEFAULT_SUPABASE_ANON_KEY = ${JSON.stringify(anonKey)};
export const DEFAULT_FUNCTION_NAME = 'deepseek-chat';
export const DEFAULT_MODEL_TYPE = 'default';
`;
}

const url = supabaseUrl;
const anonKey = (env.TOOLS_SUPABASE_ANON_KEY || '').trim();

if (!checkOnly && (!url || !anonKey)) {
  console.error('TOOLS_SUPABASE_URL / TOOLS_SUPABASE_ANON_KEY must be set in .env.local');
  process.exit(1);
}

if (!checkOnly) {
  const role = jwtRole(anonKey);
  if (role && role !== 'anon') {
    console.error(`refusing to commit a key with role="${role}" — only the anon key is public`);
    process.exit(1);
  }
  writeFileSync(target, render(url, anonKey));
  console.log(`wrote src/lib/defaults.ts  (${url}, anon key role=${role || 'not-a-jwt'})`);
  process.exit(0);
}

// --check
if (!existsSync(target)) {
  console.error('src/lib/defaults.ts is missing — run: node scripts/defaults-sync.mjs');
  process.exit(1);
}
const committed = readFileSync(target, 'utf8');
// JSON.stringify for the two values, single quotes for the literals — match what render()
// actually emits, otherwise --check silently stops checking anything.
const match = committed.match(
  /DEFAULT_SUPABASE_URL = "([^"]+)";\nexport const DEFAULT_SUPABASE_ANON_KEY = "([^"]+)";\nexport const DEFAULT_FUNCTION_NAME = '([^']+)';\nexport const DEFAULT_MODEL_TYPE = '([^']+)';/,
);
if (!match) {
  console.error('src/lib/defaults.ts does not parse — regenerate it');
  process.exit(1);
}
const [, committedUrl, committedKey, committedFn, committedModel] = match;
const role = jwtRole(committedKey);
if (role && role !== 'anon') {
  console.error(`committed key has role="${role}" — that is a secret, not the anon key`);
  process.exit(1);
}
if (!['deepseek-chat', 'relay'].includes(committedFn) || !['default', 'expert', 'vision'].includes(committedModel)) {
  console.error(`committed defaults carry an unexpected function/model default: ${committedFn} / ${committedModel}`);
  process.exit(1);
}
if (url && (committedUrl !== url || committedKey !== anonKey)) {
  console.error('committed defaults differ from .env.local — run: node scripts/defaults-sync.mjs');
  process.exit(1);
}
console.log(`defaults ok: ${committedUrl} (role=${role || 'not-a-jwt'})`);
